import sys
from sqlalchemy import inspect, text
from app import create_app
from app.extensions import db

def get_columns(connection, table_name):
    rows = connection.execute(text("SELECT column_name, data_type FROM information_schema.columns WHERE table_schema = 'public' AND table_name = :table_name"), {"table_name": table_name}).mappings().all()
    return {row["column_name"]: row["data_type"] for row in rows}

def main():
    app = create_app()
    with app.app_context():
        if db.engine.dialect.name != "postgresql":
            raise RuntimeError("تم إيقاف الترحيل: قاعدة البيانات ليست PostgreSQL.")
        try:
            with db.engine.begin() as connection:
                print("🔄 جاري تطبيق التعديلات على قاعدة البيانات الحالية...")
                
                connection.execute(text("ALTER TABLE public.users ADD COLUMN IF NOT EXISTS is_verified BOOLEAN NOT NULL DEFAULT FALSE"))
                connection.execute(text("ALTER TABLE public.deposits ADD COLUMN IF NOT EXISTS transaction_id VARCHAR(100)"))
                connection.execute(text("ALTER TABLE public.deposits ADD COLUMN IF NOT EXISTS receipt_image TEXT"))
                connection.execute(text("""
                    CREATE TABLE IF NOT EXISTS public.financial_ledger (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id INTEGER NOT NULL REFERENCES public.users(id),
                        action_type VARCHAR(50) NOT NULL,
                        amount NUMERIC(14, 4) NOT NULL,
                        balance_before NUMERIC(14, 4) NOT NULL,
                        balance_after NUMERIC(14, 4) NOT NULL,
                        reference VARCHAR(100),
                        description VARCHAR(255),
                        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                """))
                
                connection.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS uq_financial_ledger_action_reference ON public.financial_ledger (action_type, reference)"))
            print("✅ نجح الترحيل المباشر لقاعدة البيانات.")
        except Exception as exc:
            print(f"❌ فشل الترحيل؛ أُلغيت المعاملة: {exc}", file=sys.stderr)
            raise SystemExit(1)

if __name__ == "__main__":
    main()
